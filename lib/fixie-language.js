function isKnownTranslatedValue(original, currentValue) {
  if (currentValue === original) return true;

  return Object.keys(TRANSLATIONS).some((languageCode) => translateWithSpacing(original, languageCode) === currentValue);
}

function normalizeText(value) {
  return String(value).replace(/\s+/g, " ").trim();
}

function translateExact(value, languageCode) {
  const normalized = normalizeText(value);
  if (!normalized || languageCode === "en") return normalized;
  const exactTranslation = TRANSLATIONS[languageCode]?.[normalized];
  if (exactTranslation) return exactTranslation;

  const progressMatch = normalized.match(/^(\d+)% complete$/);
  if (progressMatch && TRANSLATIONS[languageCode]?.complete) {
    return `${progressMatch[1]}% ${TRANSLATIONS[languageCode].complete}`;
  }

  const dynamicTranslation = DYNAMIC_TRANSLATIONS[languageCode]?.find(([prefix]) => normalized.startsWith(prefix));
  if (!dynamicTranslation) return translateContentParts(translateServiceParts(normalized, languageCode), languageCode);

  const [sourcePrefix, translatedPrefix] = dynamicTranslation;
  return `${translatedPrefix}${normalized.slice(sourcePrefix.length)}`;
}

function translateServiceParts(value, languageCode) {
  const dictionary = SERVICE_TRANSLATIONS[languageCode];
  if (!dictionary) return value;

  const sourcePhrases = Object.keys(dictionary)
    .filter((phrase) => phrase.length > 2 && value.includes(phrase))
    .sort((a, b) => b.length - a.length);

  if (sourcePhrases.length === 0) return value;

  return sourcePhrases.reduce((translatedValue, phrase) => translatedValue.replaceAll(phrase, dictionary[phrase]), value);
}

function replaceCaseInsensitive(value, source, replacement) {
  return value.replace(new RegExp(`\\b${source.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\b`, "gi"), replacement);
}

function translateContentParts(value, languageCode) {
  const dictionary = REQUEST_CONTENT_TRANSLATIONS[languageCode];
  if (!dictionary) return value;

  const exactMatch = dictionary[value];
  if (exactMatch) return exactMatch;

  return Object.keys(dictionary)
    .filter((phrase) => phrase.length > 2)
    .sort((a, b) => b.length - a.length)
    .reduce((translatedValue, phrase) => replaceCaseInsensitive(translatedValue, phrase, dictionary[phrase]), value);
}

function translateWithSpacing(value, languageCode) {
  const leading = String(value).match(/^\s*/)?.[0] || "";
  const trailing = String(value).match(/\s*$/)?.[0] || "";
  const translated = translateExact(value, languageCode);
  return `${leading}${translated}${trailing}`;
}

function translateTextNode(node, languageCode) {
  if (node.parentElement?.closest?.("[data-fixie-no-translate='true']")) return;

  const currentValue = node.nodeValue;
  const storedOriginal = textOriginals.get(node);
  if (!storedOriginal || !isKnownTranslatedValue(storedOriginal, currentValue)) {
    textOriginals.set(node, currentValue);
  }

  const original = textOriginals.get(node);
  const translated = languageCode === "en" ? original : translateWithSpacing(original, languageCode);
  if (node.nodeValue !== translated) node.nodeValue = translated;
}

function translateAttribute(element, attrName, languageCode) {
  if (element.closest?.("[data-fixie-no-translate='true']")) return;

  const currentValue = element.getAttribute(attrName);
  if (!currentValue) return;

  let originalByAttr = attrOriginals.get(element);
  if (!originalByAttr) {
    originalByAttr = {};
    attrOriginals.set(element, originalByAttr);
  }

  if (!originalByAttr[attrName] || !isKnownTranslatedValue(originalByAttr[attrName], currentValue)) {
    originalByAttr[attrName] = currentValue;
  }

  const original = originalByAttr[attrName];
  const translated = languageCode === "en" ? original : translateExact(original, languageCode);
  if (currentValue !== translated) element.setAttribute(attrName, translated);
}

function walkAndTranslate(root, languageCode) {
  if (!root) return;

  if (root.nodeType === Node.TEXT_NODE) {
    translateTextNode(root, languageCode);
    return;
  }

  if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;

  if (root.nodeType === Node.ELEMENT_NODE) {
    ["placeholder", "aria-label", "title"].forEach((attrName) => translateAttribute(root, attrName, languageCode));
  }

  root.childNodes?.forEach((child) => walkAndTranslate(child, languageCode));
}

export function applyFixieLanguage(languageCode = "en") {
  if (Platform.OS !== "web" || typeof document === "undefined") return;

  if (window.__fixieLanguageObserver) window.__fixieLanguageObserver.disconnect();

  document.documentElement.lang = languageCode;
  document.documentElement.dir = languageCode === "ar" ? "rtl" : "ltr";
  walkAndTranslate(document.body, languageCode);

  const observer = new MutationObserver((mutations) => {
    mutations.forEach((mutation) => {
      mutation.addedNodes.forEach((node) => walkAndTranslate(node, languageCode));
      if (mutation.type === "characterData") walkAndTranslate(mutation.target, languageCode);
    });
  });

  observer.observe(document.body, { childList: true, subtree: true, characterData: true });
  window.__fixieLanguageObserver = observer;
}
